"use client";

import { AlertTriangle, BookOpen, ChevronDown, Download, Info, Loader2, Play, Plus, SlidersHorizontal, Trash2 } from "lucide-react";
import { useMemo, useState } from "react";

import Pagination from "@/components/shared/Pagination";
import PageLayout from "@/components/shared/PageLayout";
import { Select } from "@/components/shared/Select";
import { Button } from "@/components/ui/button";
import { LabeledCheckbox as Checkbox } from "@/components/shared/LabeledCheckbox";
import { useDialog } from "@/components/shared/dialog";
import { periodRange, type PeriodKind } from "@/lib/api/weinvoice/checks";
import { partnerOf } from "@/lib/api/weinvoice/invoices";
import { ACCOUNTS, accName, defaults, proposeJournal, removeRule, saveRule, type CaseKey, type JournalResult, type Regime } from "@/lib/api/weinvoice/journal";
import { fmtDate, fmtMoney } from "@/lib/weinvoice/format";
import { useTranslation } from "@/lib/i18n";
import { useStore } from "@/lib/api/weinvoice/store";
import type { Direction } from "@/lib/weinvoice/types";
import { cn } from "@/lib/utils";

const ACC_LIST = Object.keys(ACCOUNTS);

function AccChip({ a, tone }: { a: string; tone: "debit" | "credit" }) {
    return (
        <span className={cn("inline-flex items-center gap-1.5 rounded-md px-2 py-1 text-wb-12 ring-1", tone === "debit" ? "bg-brand-softer text-wb-ntrl-8 ring-brand/15" : "bg-wb-status-approved-bg text-wb-ntrl-8 ring-wb-status-approved-text/15")}>
            <b className={tone === "debit" ? "text-brand" : "text-wb-status-approved-text"}>{a}</b>
            {accName(a)}
        </span>
    );
}

/** Tự động hạch toán (M06-F07) — Invoy layout: kỳ + chế độ → Lập định khoản → sửa TK → Xuất Excel. */
export default function JournalPage() {
    const { t } = useTranslation();
    const { toast, confirm } = useDialog();
    const taxId = useStore((s) => s.activeTaxId);
    const rulesRaw = useStore((s) => s.journalRules);
    const rules = useMemo(() => rulesRaw ?? [], [rulesRaw]);
    useStore((s) => s.invoices);

    const now = new Date();
    const [kind, setKind] = useState<PeriodKind>("month");
    const [n, setN] = useState(now.getMonth() === 0 ? 12 : now.getMonth());
    const [year, setYear] = useState(now.getMonth() === 0 ? now.getFullYear() - 1 : now.getFullYear());
    const [regime, setRegime] = useState<Regime>("tt200");
    const [mtt, setMtt] = useState(false);
    const range = periodRange(kind, n, year);

    const [busy, setBusy] = useState(false);
    const [res, setRes] = useState<JournalResult | null>(null);
    const [edits, setEdits] = useState<Record<string, { debit?: string; credit?: string }>>({});
    const [dir, setDir] = useState<"all" | Direction>("all");
    const [page, setPage] = useState(1);
    const [size, setSize] = useState(50);
    const [rulesOpen, setRulesOpen] = useState(false);

    const key = `${taxId}|${range.from}|${range.to}|${regime}|${mtt}`;
    const [stamp, setStamp] = useState(key);
    if (stamp !== key) { setStamp(key); setRes(null); setEdits({}); }

    const run = async () => {
        setBusy(true);
        const r = await proposeJournal({ taxId, from: range.from, to: range.to, regime, includeCashRegister: mtt });
        setRes(r); setEdits({}); setPage(1); setBusy(false);
    };

    const rows = useMemo(() => (res?.entries ?? []).map((e) => ({ ...e, ...edits[e.id], edited: !!edits[e.id] })).filter((e) => dir === "all" || e.direction === dir), [res, edits, dir]);
    const total = rows.reduce((a, e) => a + e.amount, 0);
    const editedCount = Object.keys(edits).length;

    /*
     * Excel export is generated by the backend (repo rule: no workbook is built
     * in the browser). Column set for the weinvoice-api endpoint, one row per
     * entry line in `rows` (current filter, with inline account edits applied):
     *   Ngày HT (posting date) · Ngày CT (voucher date) · Số CT (voucher no.) ·
     *   Diễn giải · TK Nợ · TK Có · Số tiền · Mã đối tượng · Tên đối tượng
     * (+ optional Loại = Mua vào / Bán ra). Not available in this static build.
     */
    const exportXlsx = () => {
        toast(t("jn.export_unavailable"), "info");
    };

    const def = defaults(regime);
    const caseRows: { k: CaseKey }[] = [{ k: "service" }, { k: "goods" }, { k: "sales" }];

    return (
        <PageLayout>
            <div className="mx-auto flex w-full max-w-[1180px] flex-col gap-4 py-6">
                <div>
                    <h1 className="flex items-center gap-2 text-wb-22 font-bold tracking-wb-tight text-wb-dark">
                        <BookOpen className="size-6 text-wb-ntrl-7" />
                        {t("jn.title")}
                        <span className="rounded-full bg-wb-warn-bg px-2 py-0.5 text-wb-11 font-bold text-wb-warn-text ring-1 ring-wb-warn-border">{t("jn.beta")}</span>
                    </h1>
                    <p className="mt-1 text-wb-13 text-wb-ntrl-6">{t("jn.subtitle")}</p>
                    <div className="mt-2 flex flex-wrap gap-2">
                        {[1, 2, 3].map((i) => (
                            <span key={i} className="rounded-md bg-wb-bg-sidebar px-2.5 py-1 text-wb-12 font-medium text-wb-ntrl-7">{t(`jn.step${i}`)}</span>
                        ))}
                    </div>
                </div>
                <p className="flex items-start gap-2 rounded-lg bg-wb-warn-bg px-4 py-3 text-wb-13 text-wb-warn-text ring-1 ring-wb-warn-border">
                    <AlertTriangle className="mt-0.5 size-4 shrink-0" />
                    <span>{t("jn.warn")}</span>
                </p>

                {/* filters */}
                <div className="flex flex-wrap items-center gap-2 rounded-lg bg-white p-4 shadow-wb-card">
                    <Select value={kind} width={140} options={(["month", "quarter", "year"] as const).map((k) => ({ value: k, label: t(`jn.by_${k}`) }))} onChange={(v) => { setKind(v); setN(v === "quarter" ? Math.min(4, Math.ceil(n / 3)) : v === "month" ? Math.min(12, n) : 1); }} />
                    {kind !== "year" && (
                        <Select value={String(n)} width={120} options={Array.from({ length: kind === "month" ? 12 : 4 }, (_, i) => ({ value: String(i + 1), label: t(kind === "month" ? "per.month_n" : "per.quarter_n", { n: i + 1 }) }))} onChange={(v) => setN(Number(v))} />
                    )}
                    <Select value={String(year)} width={120} options={[2025, 2026].map((y) => ({ value: String(y), label: t("per.year_n", { n: y }) }))} onChange={(v) => setYear(Number(v))} />
                    <span className="ml-2 text-wb-13 text-wb-ntrl-7">{t("jn.regime")}</span>
                    <Select value={regime} width={190} options={[{ value: "tt200", label: t("jn.tt200") }, { value: "tt133", label: t("jn.tt133") }]} onChange={setRegime} />
                    <span className="ml-2"><Checkbox checked={mtt} onChange={setMtt} label={t("jn.include_mtt")} /></span>
                    <Button size="md" className="ml-auto" variant="primary" icon={busy ? <Loader2 className="animate-spin" /> : <Play />} disabled={busy} onClick={run}>
                        {t("jn.run")}
                    </Button>
                </div>

                {/* rules */}
                <div className="rounded-lg bg-white shadow-wb-card">
                    <button type="button" onClick={() => setRulesOpen((x) => !x)} className="flex w-full cursor-pointer items-center gap-2 px-4 py-3 text-left">
                        <SlidersHorizontal className="size-4 text-wb-ntrl-7" />
                        <span className="text-wb-14 font-semibold">{t("jn.rules", { n: rules.length })}</span>
                        <span className="ml-auto flex items-center gap-1 text-wb-12 text-wb-ntrl-6">{rulesOpen ? t("jn.collapse") : t("jn.expand")}<ChevronDown className={cn("size-4 transition-transform", rulesOpen && "rotate-180")} /></span>
                    </button>
                    {rulesOpen && <RulesPanel onDelete={async (id) => { if (await confirm({ title: t("jn.rule_delete"), danger: true, confirmLabel: t("common.delete") })) removeRule(id); }} />}
                </div>

                {/* defaults */}
                <div className="rounded-lg bg-white p-4 shadow-wb-card">
                    <p className="mb-2 flex items-center gap-2 text-wb-14 font-semibold"><Info className="size-4 text-wb-ntrl-7" />{t("jn.default_title")}<span className="text-wb-12 font-normal text-wb-ntrl-6">{t("jn.default_hint")}</span></p>
                    <table className="w-full text-wb-13">
                        <thead>
                            <tr className="border-b border-wb-table-border text-left text-wb-12 text-wb-ntrl-6">
                                <th className="w-[160px] py-2 font-medium">{t("jn.case")}</th>
                                <th className="py-2 font-medium">{t("jn.debit")}</th>
                                <th className="py-2 font-medium">{t("jn.credit")}</th>
                            </tr>
                        </thead>
                        <tbody>
                            {caseRows.map(({ k }) => (
                                <tr key={k} className="border-b border-wb-table-border last:border-0">
                                    <td className="py-2.5 font-semibold">{t(`jn.case.${k}`)}</td>
                                    <td className="py-2.5"><div className="flex flex-wrap gap-1.5">{def[k].debit.map((a) => <AccChip key={a} a={a} tone="debit" />)}</div></td>
                                    <td className="py-2.5"><div className="flex flex-wrap gap-1.5">{def[k].credit.map((a) => <AccChip key={a} a={a} tone="credit" />)}</div></td>
                                </tr>
                            ))}
                        </tbody>
                    </table>
                    <p className="mt-2 text-wb-12 text-wb-ntrl-6">{t("jn.default_note")}</p>
                </div>

                {/* result */}
                {res && (
                    <div className="rounded-lg bg-white p-4 shadow-wb-card">
                        <div className="mb-3 flex flex-wrap items-center gap-2">
                            <span className="rounded-md bg-brand-softer px-2.5 py-1 text-wb-12 font-semibold text-brand">{t("jn.sum_inv", { n: res.invoices })}</span>
                            <span className="rounded-md bg-wb-bg-sidebar px-2.5 py-1 text-wb-12 font-semibold text-wb-ntrl-7">{t("jn.sum_entries", { n: res.entries.length })}</span>
                            {res.byRule > 0 && <span className="rounded-md bg-wb-status-approved-bg px-2.5 py-1 text-wb-12 font-semibold text-wb-status-approved-text">{t("jn.sum_rule", { n: res.byRule })}</span>}
                            {editedCount > 0 && <span className="rounded-md bg-wb-warn-bg px-2.5 py-1 text-wb-12 font-semibold text-wb-warn-text">{t("jn.sum_edited", { n: editedCount })}</span>}
                            {(res.skipped.cancelled + res.skipped.replaced + res.skipped.cashRegister) > 0 && (
                                <span className="text-wb-12 text-wb-ntrl-6">{t("jn.skipped", { c: res.skipped.cancelled, r: res.skipped.replaced, m: res.skipped.cashRegister })}</span>
                            )}
                            <div className="ml-auto flex items-center gap-2">
                                <div className="flex rounded-md bg-wb-bg-sidebar p-0.5">
                                    {(["all", "purchase", "sales"] as const).map((d) => (
                                        <button key={d} type="button" onClick={() => { setDir(d); setPage(1); }} className={cn("h-8 cursor-pointer rounded px-3 text-wb-13 font-semibold", dir === d ? "bg-white text-brand shadow-wb-btn" : "text-wb-ntrl-7")}>
                                            {d === "all" ? t("jn.all") : t(`dir.${d}`)}
                                        </button>
                                    ))}
                                </div>
                                <Button size="md" variant="primary" icon={<Download />} disabled={!rows.length} onClick={exportXlsx}>{t("jn.export")}</Button>
                            </div>
                        </div>
                        <datalist id="jn-acc">{ACC_LIST.map((a) => <option key={a} value={a}>{accName(a)}</option>)}</datalist>
                        <div className="overflow-x-auto rounded-md ring-1 ring-wb-table-border">
                            <table className="w-full min-w-[960px] border-collapse text-wb-13">
                                <thead>
                                    <tr className="h-[var(--h-wb-table-head)] border-b border-wb-table-border bg-wb-bg-sidebar text-left font-semibold text-wb-ntrl-8">
                                        <th className="px-3">{t("jn.c.date")}</th>
                                        <th className="px-3">{t("jn.c.ref")}</th>
                                        <th className="px-3">{t("jn.c.partner")}</th>
                                        <th className="px-3">{t("jn.c.desc")}</th>
                                        <th className="w-[96px] px-3">{t("jn.c.debit")}</th>
                                        <th className="w-[96px] px-3">{t("jn.c.credit")}</th>
                                        <th className="px-3 text-right">{t("jn.c.amount")}</th>
                                    </tr>
                                </thead>
                                <tbody>
                                    {rows.slice((page - 1) * size, page * size).map((e) => (
                                        <tr key={e.id} className={cn("border-b border-wb-table-border align-top", e.line === "vat" && "bg-wb-bg-sidebar/40")}>
                                            <td className="px-3 py-2 whitespace-nowrap">{e.line === "main" ? fmtDate(e.date) : ""}</td>
                                            <td className="px-3 py-2 font-mono text-wb-12 whitespace-nowrap">{e.line === "main" ? e.ref : ""}</td>
                                            <td className="max-w-[200px] px-3 py-2">
                                                {e.line === "main" && (
                                                    <>
                                                        <p className="truncate">{e.partnerName}</p>
                                                        <p className="font-mono text-wb-11 text-wb-ntrl-6">{e.partnerTaxId}</p>
                                                    </>
                                                )}
                                            </td>
                                            <td className="max-w-[280px] px-3 py-2">
                                                <p className="truncate" title={e.desc}>{e.desc}</p>
                                                {e.line === "main" && (
                                                    <span className={cn("mt-0.5 inline-block rounded-sm px-1.5 text-wb-11 font-medium", e.ruleId ? "bg-wb-status-approved-bg text-wb-status-approved-text" : "bg-wb-bg-sidebar text-wb-ntrl-6")}>
                                                        {e.ruleId ? t("jn.by_rule") : t(`jn.case.${e.caseKey}`)}
                                                    </span>
                                                )}
                                            </td>
                                            {(["debit", "credit"] as const).map((side) => (
                                                <td key={side} className="px-3 py-1.5">
                                                    <input
                                                        list="jn-acc"
                                                        value={e[side]}
                                                        title={accName(e[side])}
                                                        onChange={(ev) => setEdits((m) => ({ ...m, [e.id]: { ...m[e.id], [side]: ev.target.value.trim() } }))}
                                                        className={cn("h-8 w-[76px] rounded-md px-2 font-mono text-wb-13 font-semibold shadow-wb-outline outline-none focus:shadow-wb-focus", side === "debit" ? "text-brand" : "text-wb-status-approved-text", edits[e.id]?.[side] && "bg-wb-warn-bg")}
                                                    />
                                                </td>
                                            ))}
                                            <td className="px-3 py-2 text-right font-semibold tabular-nums">{fmtMoney(e.amount)}</td>
                                        </tr>
                                    ))}
                                    {rows.length === 0 && <tr><td colSpan={7} className="px-3 py-8 text-center text-wb-ntrl-6">{t("jn.empty")}</td></tr>}
                                </tbody>
                                {rows.length > 0 && (
                                    <tfoot>
                                        <tr className="bg-wb-bg-sidebar font-semibold">
                                            <td colSpan={6} className="px-3 py-2.5">{t("jn.total")}</td>
                                            <td className="px-3 py-2.5 text-right tabular-nums">{fmtMoney(total)}</td>
                                        </tr>
                                    </tfoot>
                                )}
                            </table>
                        </div>
                        <div className="mt-3">
                            <Pagination page={page} pageSize={size} pageCount={Math.max(1, Math.ceil(rows.length / size))} totalLabel={t("common.showing", { from: rows.length === 0 ? 0 : (page - 1) * size + 1, to: Math.min(rows.length, page * size), total: rows.length })} onPageChange={setPage} onPageSizeChange={(s) => { setSize(s); setPage(1); }} />
                        </div>
                    </div>
                )}
            </div>
        </PageLayout>
    );
}

function RulesPanel({ onDelete }: { onDelete: (id: string) => void }) {
    const { t } = useTranslation();
    const { toast } = useDialog();
    const rulesRaw = useStore((s) => s.journalRules);
    const rules = useMemo(() => rulesRaw ?? [], [rulesRaw]);
    const taxId = useStore((s) => s.activeTaxId);
    const invoices = useStore((s) => s.invoices);
    const [direction, setDirection] = useState<Direction>("purchase");
    const partners = useMemo(() => {
        const m = new Map<string, string>();
        for (const i of invoices) {
            if (i.direction !== direction || (direction === "purchase" ? i.buyerTaxId : i.sellerTaxId) !== taxId) continue;
            const p = partnerOf(i);
            m.set(p.taxId, p.name);
        }
        return [...m.entries()].sort((a, b) => a[1].localeCompare(b[1]));
    }, [invoices, direction, taxId]);
    const [partner, setPartner] = useState("");
    const [keyword, setKeyword] = useState("");
    const [main, setMain] = useState("642");
    const [counter, setCounter] = useState("331");
    const [err, setErr] = useState("");
    const input = "h-9 rounded-md px-2.5 text-wb-13 shadow-wb-outline outline-none focus:shadow-wb-focus";

    const add = () => {
        if (!partner && !keyword.trim()) return setErr(t("jn.rule_err_match"));
        if (!/^\d{3,5}$/.test(main) || !/^\d{3,5}$/.test(counter)) return setErr(t("jn.rule_err_acc"));
        saveRule({ direction, partnerTaxId: partner || undefined, keyword: keyword.trim() || undefined, main, counter });
        setPartner(""); setKeyword(""); setErr("");
        toast(t("jn.rule_saved"));
    };
    const partnerName = (id?: string) => partners.find(([k]) => k === id)?.[1] ?? id;

    return (
        <div className="border-t border-wb-table-border px-4 py-3">
            {rules.length > 0 ? (
                <table className="mb-3 w-full text-wb-13">
                    <thead>
                        <tr className="border-b border-wb-table-border text-left text-wb-12 text-wb-ntrl-6">
                            <th className="py-2 font-medium">{t("jn.r.dir")}</th>
                            <th className="py-2 font-medium">{t("jn.r.when")}</th>
                            <th className="py-2 font-medium">{t("jn.r.main")}</th>
                            <th className="py-2 font-medium">{t("jn.r.counter")}</th>
                            <th className="w-10" />
                        </tr>
                    </thead>
                    <tbody>
                        {rules.map((r) => (
                            <tr key={r.id} className="border-b border-wb-table-border last:border-0">
                                <td className="py-2">{t(`dir.${r.direction}`)}</td>
                                <td className="py-2">
                                    {r.partnerTaxId && <p>{t("jn.r.partner_is", { p: partnerName(r.partnerTaxId) ?? "" })}</p>}
                                    {r.keyword && <p>{t("jn.r.kw_is", { k: r.keyword })}</p>}
                                </td>
                                <td className="py-2"><AccChip a={r.main} tone={r.direction === "purchase" ? "debit" : "credit"} /></td>
                                <td className="py-2"><AccChip a={r.counter} tone={r.direction === "purchase" ? "credit" : "debit"} /></td>
                                <td className="py-2 text-right">
                                    <button type="button" onClick={() => onDelete(r.id)} className="cursor-pointer rounded p-1.5 text-wb-ntrl-6 hover:bg-black/5 hover:text-wb-status-rejected-text" title={t("common.delete")}><Trash2 className="size-4" /></button>
                                </td>
                            </tr>
                        ))}
                    </tbody>
                </table>
            ) : (
                <p className="mb-3 text-wb-13 text-wb-ntrl-6">{t("jn.rules_empty")}</p>
            )}
            <div className="rounded-md bg-wb-bg-sidebar p-3">
                <p className="mb-2 text-wb-13 font-semibold">{t("jn.rule_add")}</p>
                <div className="flex flex-wrap items-end gap-2">
                    <Select value={direction} width={130} options={[{ value: "purchase", label: t("dir.purchase") }, { value: "sales", label: t("dir.sales") }]} onChange={(v) => { setDirection(v); setMain(v === "purchase" ? "642" : "511"); setCounter(v === "purchase" ? "331" : "131"); setPartner(""); }} />
                    <select value={partner} onChange={(e) => setPartner(e.target.value)} className={cn(input, "max-w-[280px] bg-white")}>
                        <option value="">{t("jn.r.any_partner")}</option>
                        {partners.map(([id, name]) => <option key={id} value={id}>{id} · {name}</option>)}
                    </select>
                    <input className={cn(input, "w-[200px] bg-white")} value={keyword} onChange={(e) => setKeyword(e.target.value)} placeholder={t("jn.r.kw_ph")} />
                    <label className="flex flex-col gap-0.5 text-wb-11 text-wb-ntrl-6">
                        {direction === "purchase" ? t("jn.r.main_debit") : t("jn.r.main_credit")}
                        <input list="jn-acc-r" className={cn(input, "w-[90px] bg-white font-mono font-semibold")} value={main} onChange={(e) => setMain(e.target.value.trim())} />
                    </label>
                    <label className="flex flex-col gap-0.5 text-wb-11 text-wb-ntrl-6">
                        {direction === "purchase" ? t("jn.r.counter_credit") : t("jn.r.counter_debit")}
                        <select className={cn(input, "w-[110px] bg-white font-mono font-semibold")} value={counter} onChange={(e) => setCounter(e.target.value)}>
                            {(direction === "purchase" ? ["331", "111", "112"] : ["131", "111", "112"]).map((a) => <option key={a} value={a}>{a}</option>)}
                        </select>
                    </label>
                    <Button size="md" variant="primary" icon={<Plus />} onClick={add}>{t("jn.rule_add_btn")}</Button>
                    <datalist id="jn-acc-r">{ACC_LIST.map((a) => <option key={a} value={a}>{accName(a)}</option>)}</datalist>
                </div>
                {main && accName(main) && <p className="mt-1.5 text-wb-12 text-wb-ntrl-6">{main} — {accName(main)}</p>}
                {err && <p className="mt-2 text-wb-12 text-wb-status-rejected-text">{err}</p>}
            </div>
        </div>
    );
}
